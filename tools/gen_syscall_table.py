"""Generate core/src/syscall_table.rs (Nt* API signatures) from upstream NtRays' nt_syscalls.inc.

    python -I tools/gen_syscall_table.py <NtRays>/nt_syscalls.inc core/src/syscall_table.rs

Only the signatures are taken; syscall numbers come from the binary (stubs) or from ntdll/win32u files.
Entries are sorted by name so lookups can binary-search.
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
body = text[text.index("nt_api_descriptors[] = {"):text.index("const char *const nt_missing_apis")]

api_re = re.compile(r'^\t\{ "(\w+)", "([^"]+)", \{ (.*) \} \},?$', re.M)
arg_re = re.compile(r'\{ "([^"]+)", (?:"([^"]*)"|nullptr) \}')

apis = {}
for name, ret, args in api_re.findall(body):
    apis[name] = (ret, arg_re.findall(args))
expected = body.count('\n\t{ "')
assert len(apis) == expected, (len(apis), expected)

def lit(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')

with open(dst, "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by tools/gen_syscall_table.py from upstream NtRays nt_syscalls.inc. Do not edit.\n")
    out.write("// %d Nt* API signatures, sorted by name.\n\n" % len(apis))
    out.write("use crate::syscall::Api;\n\n#[rustfmt::skip]\npub static APIS: &[Api] = &[\n")
    for name in sorted(apis):
        ret, args = apis[name]
        a = ", ".join("(%s, %s)" % (lit(t), lit(n)) for t, n in args)
        out.write("    Api { name: %s, ret: %s, args: &[%s] },\n" % (lit(name), lit(ret), a))
    out.write("];\n")
print(len(apis), "APIs")
