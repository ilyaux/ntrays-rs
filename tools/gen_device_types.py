"""Generate core/src/ioctl_device_types.rs (FILE_DEVICE_* names) from the Windows SDK's winioctl.h.

    python -I tools/gen_device_types.py "<Windows Kits>/10/Include/<version>/um/winioctl.h" core/src/ioctl_device_types.rs

Only the documented constant names and values are taken; they name IOCTL device types for display.
"""
import os, re, sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8", errors="replace").read()
pairs = {}
for name, value in re.findall(r"^#define (FILE_DEVICE_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+)\b", text, re.M):
    v = int(value, 16)
    assert v <= 0xFFFF, (name, value)
    assert v not in pairs, ("duplicate value", name, pairs.get(v))
    pairs[v] = name
sdk = os.path.basename(os.path.dirname(os.path.dirname(os.path.abspath(src))))

with open(dst, "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by tools/gen_device_types.py from winioctl.h of Windows SDK %s. Do not edit.\n" % sdk)
    out.write("// %d FILE_DEVICE_* device types, sorted by value.\n\n" % len(pairs))
    out.write("#[rustfmt::skip]\npub(crate) static DEVICE_TYPES: &[(u16, &str)] = &[\n")
    for v in sorted(pairs):
        out.write("    (0x%04X, \"%s\"),\n" % (v, pairs[v]))
    out.write("];\n")
print(len(pairs), "device types from SDK", sdk)
