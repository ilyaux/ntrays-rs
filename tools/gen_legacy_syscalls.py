"""Freeze the ORIGINAL NtRays IDB indexes, never the current alphabetic API table.

    python -I tools/gen_legacy_syscalls.py <NtRays>/nt_syscalls.inc core/src/legacy_syscalls.rs
"""
import hashlib
import re
import sys
from pathlib import Path

src, dst = map(Path, sys.argv[1:])
data = src.read_bytes()
assert hashlib.sha256(data).hexdigest() == "c7929397db55812e0307845e700169a0b36ff2687e992156c0207c16f054bc26", "unknown legacy table: do not change existing IDB index meanings"
text = data.decode("utf-8")
definitions, remainder = text.split("const char *const nt_missing_apis[] = {", 1)
missing, presets = remainder.split("const std::pair<const char *, nt_syscall_map_t> nt_syscall_maps[] = {", 1)
names = re.findall(r'^\t\{ "(\w+)",', definitions, re.M) + re.findall(r'"(Nt\w+)"', missing)
maps = re.findall(r'\{ "([^"]+)", \{\s*\{ ([\d, ]*) \},\s*\{ ([\d, ]*) \}\s*\} \}', presets)
assert len(names) == 2254 and len(set(names)) == len(names), len(names)
assert len(maps) == 32, len(maps)
lines = ["// Generated by tools/gen_legacy_syscalls.py; legacy indexes are one-based and immutable.",
         f"// Upstream nt_syscalls.inc SHA-256: {hashlib.sha256(data).hexdigest()}",
         "pub const API_NAMES: &[&str] = &["]
lines += [f'    "{name}",' for name in names]
lines += ["];", "", "#[rustfmt::skip]", "pub const PRESETS: &[(&[u16], &[u16])] = &["]
for name, nt, win32k in maps:
    values = [[int(n) for n in part.split(",") if n.strip()] for part in (nt, win32k)]
    assert all(0 <= v <= len(names) for part in values for v in part)
    lines += [f"    // {name}", f"    (&[{nt.replace(' ', '')}], &[{win32k.replace(' ', '')}]),"]
lines += ["];", ""]
dst.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(len(names), "legacy API names,", len(maps), "legacy presets")
